// react-flagpack's own alpha-2 alias set is missing a plain "GB.svg" for the United Kingdom —
// it only ships "GBR.svg"/"GB-UKM.svg" (identical, both the Union Jack) alongside the four
// constituent-country flags (GB-ENG/SCT/WLS/NIR) — so the flag *asset* code has to differ from
// the ISO country code here. `countryForTimezone`'s "GB" is still correct and unchanged (it also
// feeds `Intl.DisplayNames`, which only recognizes real ISO codes); this only remaps which SVG
// file gets requested.
const FLAG_ASSET_CODE_OVERRIDE = { GB: "GBR" } satisfies Record<string, string>;

/** The code to pass to `<Flag code={...}>` for a country — usually just the ISO code itself,
 * except where react-flagpack's own asset set doesn't ship a same-named alpha-2 file for it. */
export function flagAssetCode(countryCode: string): string {
  return Object.hasOwn(FLAG_ASSET_CODE_OVERRIDE, countryCode)
    ? // SAFETY: `Object.hasOwn` just above confirmed `countryCode` is actually one of this
      // object's keys.
      FLAG_ASSET_CODE_OVERRIDE[countryCode as keyof typeof FLAG_ASSET_CODE_OVERRIDE]
    : countryCode;
}

const regionNames = new Intl.DisplayNames(["en"], { type: "region" });

/** `TIMEZONE_COUNTRY`'s inferred type is a closed set of literal keys (kept that way — see the
 * `satisfies` above — so a typo in the table itself would be a type error), so an arbitrary
 * runtime `tz` string can't index it directly; `Object.hasOwn` narrows it back to a known key
 * first. */
export function countryForTimezone(tz: string): string | undefined {
  return Object.hasOwn(TIMEZONE_COUNTRY, tz)
    ? // SAFETY: `Object.hasOwn` just above confirmed `tz` is actually one of this object's keys.
      TIMEZONE_COUNTRY[tz as keyof typeof TIMEZONE_COUNTRY]
    : undefined;
}

/** Human-readable country name for a zone's mapped country code (e.g. "Germany" for
 * "Europe/Berlin"), for the time zone picker's search text — lets typing "Germany" find it,
 * not just "Berlin". `undefined` when the zone isn't in the table above, or the runtime's
 * `Intl.DisplayNames` doesn't recognize the code (neither should happen for a real country
 * code, but this is display-only polish, not worth a thrown error either way). */
export function countryNameForTimezone(tz: string): string | undefined {
  const code = countryForTimezone(tz);
  if (!code) return undefined;
  try {
    return regionNames.of(code);
  } catch {
    return undefined;
  }
}

